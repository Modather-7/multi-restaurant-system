    /*
    |--------------------------------------------------------------------------
    | FUNCTIONS
    |--------------------------------------------------------------------------
    */
    public function branchProducts()
    {
        return $this -> hasMany(BranchProduct::class);
    }

    public function orders()
    {
        return $this -> hasMany(Order::class);
    }

    public function products()
    {
        return $this ->belongsToMany(Product::class)
                        ->withPivot('quantity')
                        ->withTimestamps();
    }

